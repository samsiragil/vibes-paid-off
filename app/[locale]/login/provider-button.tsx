"use client";

import { useFormStatus } from "react-dom";
import { buttonStyles } from "@/components/ui/button";

/** One submit button per provider inside the login form; disables both while redirecting. */
export function ProviderButton({
  provider,
  label,
}: {
  provider: "github" | "google";
  label: string;
}) {
  const { pending, data } = useFormStatus();
  const isThis = pending && data?.get("provider") === provider;

  return (
    <button
      type="submit"
      name="provider"
      value={provider}
      disabled={pending}
      aria-busy={isThis}
      className={buttonStyles({ variant: "outline", size: "lg", className: "w-full" })}
    >
      {provider === "github" ? <GitHubIcon /> : <GoogleIcon />}
      <span>{label}</span>
      {isThis ? <span aria-hidden="true">…</span> : null}
    </button>
  );
}

